const assert = require('node:assert/strict');
(async () => {
  const { deriveInputCalibration, createInputProfiles, inputDeviceKey } = await import('../src/inputCalibration.js');
  assert.equal(inputDeviceKey({ deviceId:'default' }), null);
  assert.equal(inputDeviceKey({ deviceId:'a' }), 'a:');
  assert.notEqual(inputDeviceKey({ deviceId:'default',groupId:'a' }), inputDeviceKey({ deviceId:'default',groupId:'b' }));
  const { cameraFraming } = await import('../src/cameraFraming.js');
  const samples = (level) => new Array(50).fill(level);
  const quiet = deriveInputCalibration(samples(0.005), samples(0.15));
  assert.equal(quiet.ok, true); assert.equal(quiet.threshold, 0.05);
  const noisy = deriveInputCalibration(samples(0.025), samples(0.2));
  assert.equal(noisy.ok, true); assert.ok(noisy.threshold > 0.05 && noisy.threshold <= 0.15);
  assert.equal(deriveInputCalibration(samples(0.1), samples(0.4)).reason, 'noise');
  assert.equal(deriveInputCalibration(samples(0.005), samples(0.02)).reason, 'signal');
  assert.equal(deriveInputCalibration(samples(0.005), samples(0.99)).reason, 'clipping');
  assert.equal(deriveInputCalibration([0], samples(0.2)).reason, 'samples');
  assert.equal(deriveInputCalibration(samples(NaN), samples(0.2)).reason, 'invalid');
  assert.equal(deriveInputCalibration(samples(-1), samples(0.2)).reason, 'invalid');
  const spike = samples(0.005); spike[0] = 0.5;
  assert.equal(deriveInputCalibration(spike, samples(0.15)).threshold, 0.05);
  const oneSound = samples(0); oneSound[0] = 0.4;
  assert.equal(deriveInputCalibration(samples(0.005), oneSound).reason, 'signal');
  const profiles = createInputProfiles(); const a = { deviceId: 'a', generation: 1 };
  assert.equal(profiles.threshold(0.05, a, 100), 0.05);
  assert.equal(profiles.apply(noisy, a, 100), true);
  assert.equal(profiles.threshold(0.05, { deviceId: 'a', generation: 3 }, 200), noisy.threshold);
  assert.equal(profiles.threshold(0.05, { deviceId: 'b', generation: 3 }, 200), 0.05);
  assert.equal(profiles.threshold(0.05, a, 600101), 0.05);
  profiles.apply(noisy, { deviceId: null, generation: 4 }, 0);
  assert.equal(profiles.threshold(0.05, { deviceId: null, generation: 4 }, 200), noisy.threshold);
  assert.equal(profiles.threshold(0.05, { deviceId: null, generation: 5 }, 200), 0.05);
  profiles.clear(); assert.equal(profiles.threshold(0.05, a, 200), 0.05);
  assert.equal(profiles.apply({ ok: true, threshold: 0.8 }, a, 0), false);
  assert.equal(profiles.apply({ ok: false, threshold: 0.1 }, a, 0), false);
  const lm = Array.from({ length: 33 }, () => ({ x: 0.5, y: 0.5, visibility: 0 }));
  for (const [i, x, y] of [[7,.35,.2],[8,.65,.2],[11,.3,.4],[12,.7,.4],[13,.25,.5],[15,.3,.6],[17,.32,.63],[19,.34,.63]]) lm[i] = { x, y, visibility: 1 };
  assert.equal(cameraFraming(lm, 'left', 'all').ready, true);
  assert.equal(cameraFraming(null, 'left', 'all').reason, 'nobody');
  const copy = () => JSON.parse(JSON.stringify(lm));
  let bad = copy(); bad[15].visibility = 0;
  assert.equal(cameraFraming(bad, 'left', 'wrist').reason, 'hand');
  assert.equal(cameraFraming(bad, 'left', 'shoulder').ready, true);
  bad = copy(); bad[11].x = -0.1;
  assert.equal(cameraFraming(bad, 'left', 'all').reason, 'shoulders');
  bad = copy(); bad[7].visibility = 0;
  assert.equal(cameraFraming(bad, 'left', 'shoulder').reason, 'ears');
  bad = copy(); bad[12].x = .35;
  assert.equal(cameraFraming(bad, 'left', 'all').reason, 'distance');
  bad = copy(); bad[19].x = NaN;
  assert.equal(cameraFraming(bad, 'left', 'wrist').reason, 'hand');
  assert.equal(cameraFraming(lm, 'right', 'wrist').reason, 'hand');
  console.log('PASS calibration validity/noise/signal/clipping, device/expiry/reset and camera framing contracts');
})().catch((error) => { console.error(error); process.exitCode = 1; });
